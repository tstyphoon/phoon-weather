"""台灣縣市對照：使用者可以打「台北」「臺北」「新竹」等，統一成氣象署的縣市名稱。"""
from __future__ import annotations

# 氣象署縣市名稱 -> (緯度, 經度)
TAIWAN_COUNTIES: dict[str, tuple[float, float]] = {
    "臺北市": (25.04, 121.56), "新北市": (25.01, 121.46), "桃園市": (24.99, 121.30),
    "臺中市": (24.15, 120.67), "臺南市": (22.99, 120.21), "高雄市": (22.63, 120.30),
    "基隆市": (25.13, 121.74), "新竹縣": (24.84, 121.01), "新竹市": (24.81, 120.97),
    "苗栗縣": (24.56, 120.82), "彰化縣": (24.07, 120.54), "南投縣": (23.96, 120.97),
    "雲林縣": (23.71, 120.43), "嘉義縣": (23.45, 120.25), "嘉義市": (23.48, 120.45),
    "屏東縣": (22.55, 120.55), "宜蘭縣": (24.70, 121.74), "花蓮縣": (23.99, 121.60),
    "臺東縣": (22.76, 121.14), "澎湖縣": (23.57, 119.58), "金門縣": (24.45, 118.38),
    "連江縣": (26.16, 119.95),
}

# 簡稱優先順序：市在前（新竹、嘉義預設選市）
_ORDER = sorted(TAIWAN_COUNTIES, key=lambda n: (n.endswith("縣"), n))


def _norm(text: str) -> str:
    return text.replace("台", "臺").strip()


def find_county(text: str) -> str | None:
    """文字裡有提到的台灣縣市，回傳氣象署名稱；沒有回傳 None。
    先比對完整名稱，再比對省略「市／縣」的簡稱。"""
    t = _norm(text)
    for name in TAIWAN_COUNTIES:
        if name in t:
            return name
    for name in _ORDER:
        if name[:-1] in t:
            return name
    return None
